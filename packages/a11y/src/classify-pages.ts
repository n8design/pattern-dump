// Writes page-rule-tiers.generated.json from the page classifier (page-classifier.ts) and prints each rule's verdict.
// Run: npm run classify-pages --workspace @pattern-dump/a11y
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { classifyPages } from "./page-classifier.js";
import { PAGE_TAGS } from "./page.js";

async function main() {
  const { axeVersion, jsdom, browser, why } = await classifyPages();
  for (const id of [...jsdom, ...browser]) console.log(`  ${jsdom.includes(id) ? "jsdom  " : "browser"} ${id.padEnd(36)} ${why[id]}`);
  const artifact = {
    _note: "Generated by packages/a11y/src/page-classifier.ts — do not hand-edit. Re-run: npm run classify-pages --workspace @pattern-dump/a11y",
    axeVersion, tags: PAGE_TAGS, jsdom, browser,
  };
  writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "page-rule-tiers.generated.json"), JSON.stringify(artifact, null, 2) + "\n");
  console.log(`${jsdom.length} rules decided in jsdom, ${browser.length} need a browser (axe-core ${axeVersion})`);
}

await main();
