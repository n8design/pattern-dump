// Writes page-rule-tiers.generated.json from the page classifier (page-classifier.ts) and prints each rule's verdict.
// Run: npm run classify-pages --workspace @pattern-dump/a11y (bundled into dist/ with esbuild, then run with node).
import { writeFileSync } from "node:fs";
import { classifyPages } from "./page-classifier.js";
import { PAGE_TAGS } from "./page.js";

async function main() {
  const { axeVersion, jsdom, browser, leftOut, why } = await classifyPages();
  for (const id of [...jsdom, ...browser]) console.log(`  ${jsdom.includes(id) ? "jsdom  " : "browser"} ${id.padEnd(36)} ${why[id]}`);
  const artifact = {
    _note: "Generated by packages/a11y/src/page-classifier.ts: do not hand-edit. Re-run: npm run classify-pages --workspace @pattern-dump/a11y",
    axeVersion, tags: PAGE_TAGS, jsdom, browser,
  };
  // Into src/ from either folder: the bundle runs from dist/, a sibling of src/.
  writeFileSync(new URL("../src/page-rule-tiers.generated.json", import.meta.url), JSON.stringify(artifact, null, 2) + "\n");
  console.log(`${jsdom.length} rules decided in jsdom, ${browser.length} need a browser, ${leftOut.length} left out as axe does by default: ${leftOut.join(", ")} (axe-core ${axeVersion})`);
}

await main();
